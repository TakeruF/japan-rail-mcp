import type { Station } from '../../core/schemas.js';

type StationSeed = Omit<Station, 'source' | 'countryCode' | 'name' | 'extensions'> & {
  lines?: string[];
};

const JR_EAST = 'JR East';
const JR_CENTRAL = 'JR Central';
const JR_WEST = 'JR West';
const JR_KYUSHU = 'JR Kyushu';
const JR_HOKKAIDO = 'JR Hokkaido';

function station(seed: StationSeed): Station {
  return {
    id: seed.id,
    name: seed.localName,
    localName: seed.localName,
    ...(seed.englishName === undefined ? {} : { englishName: seed.englishName }),
    aliases: seed.aliases,
    countryCode: 'JP',
    operators: seed.operators,
    ...(seed.prefecture === undefined ? {} : { prefecture: seed.prefecture }),
    extensions: {
      japan: {
        shinkansenLines: seed.lines ?? [],
        providerNames: { ekispert: seed.localName },
      },
    },
    source: {
      provider: 'japan-rail-mcp',
      dataset: 'bundled-shinkansen-station-catalog',
      retrievedAt: new Date().toISOString(),
      lastUpdated: '2026-08-25',
      license: 'Project-maintained factual metadata; upstream railway data terms remain separate',
      isRealtime: false,
    },
  };
}

